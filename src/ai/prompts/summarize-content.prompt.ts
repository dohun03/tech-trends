import { SummarizeContentParams } from '../interfaces/ai.interface';

export const buildSummarizeContentPrompt = (params: SummarizeContentParams): string => {
  const { title, content } = params;

  return `
  당신은 IT 트렌드 전문 에디터이자 수석 백엔드 엔지니어입니다.
  제공된 개발 블로그 글의 핵심 내용을 한국인 백엔드 개발자가 바로 실무에 참고할 수 있도록 요약하세요.

  [원문 정보]
  - 영문 제목: ${title}
  - 본문 내용 (블로그 아티클 또는 Q&A): ${content}

  [문체 및 작성 규칙 - 엄격 준수]
  1. 제3자 관점 표현 절대 금지: "이 글은", "저자는", "본문에서는", "언급합니다" 등의 표현을 절대 사용하지 마세요.
  2. 직접 설명체 사용: 기술 개요 문서를 작성하듯 직접적인 문체(~합니다, ~입니다)를 사용하세요.
  3. 용어 유지: 영문 기술 용어는 원어 철자를 그대로 유지하세요.

  [작성 가이드 및 필드별 규칙]
  1. title: 기술 직관적인 한국어 제목
  2. short_summary: 핵심 내용을 친근한 존댓말(~해요 체) 3문장 배열로 작성
  3. long_summary: 아래 마크다운 구조를 준수하여 300자~1000자 이상의 상세 요약 작성
    - 원문에 실무 주의사항이나 장단점 내용이 부족하다면 해당 항목에 "원문 내 별도 언급 없음"으로 명시하거나 관련 기술의 일반적인 주의점 1줄로 대체할 것.
  4. tags: 주요 기술 스택을 쉼표로 구분한 문자열

  [long_summary 마크다운 구조]
  ## 기술 개요 및 배경
  (기술의 등장 배경, 해결하고자 하는 문제 영역을 직접 서술)

  ## 주요 내용 및 구현 방식
  (구체적인 기술 스택, Architecture, 핵심 알고리즘, 해결 전략을 불릿 포인트 - 로 구체적으로 서술)

  ## 실무 적용 및 주의사항
  (실무 적용 시 장점, 한계점, 고려해야 할 규칙 서술)

  [응답 포맷 (JSON)]
  {
    "title": "가공된 한국어 제목",
    "short_summary": ["문장 1이에요.", "문장 2이에요.", "문장 3이에요."],
    "long_summary": "## 기술 개요 및 배경\\n...\\n\\n## 주요 내용 및 구현 방식\\n- ...\\n\\n## 실무 적용 및 주의사항\\n- ...",
    "tags": "NestJS, Redis"
  }
  `.trim();
};